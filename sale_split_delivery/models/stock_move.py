# -*- coding: utf-8 -*-
from odoo import fields, models
from odoo.tools.misc import groupby


class StockMove(models.Model):
    _inherit = 'stock.move'

    sale_split_date = fields.Date(
        string='Split Delivery Date', index=True, readonly=True,
        help='Delivery day used to group this move into a delivery order.')
    sale_split_location_id = fields.Many2one(
        'stock.location', string='Split Source Location', readonly=True,
        help='Source location requested on the sales order line; carried '
             'through every step of a multi-step delivery route.')

    def _prepare_procurement_values(self):
        # Propagate the split keys to the next step of a multi-step route
        # (ship -> pack -> pick are generated by make-to-order chaining).
        values = super()._prepare_procurement_values()
        if self.sale_split_date:
            values['sale_split_date'] = self.sale_split_date
        if self.sale_split_location_id:
            values['sale_split_location_id'] = self.sale_split_location_id
        return values

    def _assign_picking(self):
        # The native grouping key (group, locations, picking type) cannot
        # carry a date in every 16.0 revision, so batch by split day first and
        # let the standard engine do the rest within each batch.
        if len(set(self.mapped('sale_split_date'))) <= 1:
            return super()._assign_picking()
        for _split_date, moves in groupby(self, key=lambda m: m.sale_split_date):
            super(StockMove, self.env['stock.move'].concat(*moves))._assign_picking()
        return True

    def _get_new_picking_values(self):
        values = super()._get_new_picking_values()
        split_dates = set(self.mapped('sale_split_date')) - {False, None}
        if len(split_dates) == 1:
            values['sale_split_date'] = split_dates.pop()
        return values

    def _search_picking_for_assignation(self):
        self.ensure_one()
        picking = super()._search_picking_for_assignation()
        split_date = self.sale_split_date or False
        if not picking or (picking.sale_split_date or False) == split_date:
            return picking
        # The standard lookup matched a delivery order of another day: search
        # again with the same criteria plus the split day.
        domain = [
            ('group_id', '=', picking.group_id.id),
            ('location_id', '=', picking.location_id.id),
            ('location_dest_id', '=', picking.location_dest_id.id),
            ('picking_type_id', '=', picking.picking_type_id.id),
            ('printed', '=', False),
            ('immediate_transfer', '=', False),
            ('state', 'in', ['draft', 'confirmed', 'waiting',
                             'partially_available', 'assigned']),
            ('sale_split_date', '=', split_date),
        ]
        if self.partner_id and (self.location_id.usage == 'transit'
                                or self.location_dest_id.usage == 'transit'):
            domain.append(('partner_id', '=', self.partner_id.id))
        return self.env['stock.picking'].search(domain, limit=1)
