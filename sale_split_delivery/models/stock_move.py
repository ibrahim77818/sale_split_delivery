# -*- coding: utf-8 -*-
from odoo import fields, models


class StockMove(models.Model):
    _inherit = 'stock.move'

    sale_split_date = fields.Date(
        string='Split Delivery Date', index=True, readonly=True,
        help='Delivery day used to group this move into a delivery order.')
    sale_split_location_id = fields.Many2one(
        'stock.location', string='Split Source Location', readonly=True,
        help='Source location requested on the sales order line; carried '
             'through every step of a multi-step delivery route.')

    def _prepare_procurement_values(self):
        # Propagate the split keys to the next step of a multi-step route
        # (ship -> pack -> pick are generated by make-to-order chaining).
        values = super()._prepare_procurement_values()
        if self.sale_split_date:
            values['sale_split_date'] = self.sale_split_date
        if self.sale_split_location_id:
            values['sale_split_location_id'] = self.sale_split_location_id
        return values

    def _assign_picking(self):
        # Batch by split day first, then let the standard engine group each
        # batch by stock reference, locations and operation type.
        batches = {}
        for move in self:
            batches.setdefault(move.sale_split_date or False, []).append(move.id)
        if len(batches) <= 1:
            return super()._assign_picking()
        for move_ids in batches.values():
            super(StockMove, self.browse(move_ids))._assign_picking()
        return True

    def _get_new_picking_values(self):
        values = super()._get_new_picking_values()
        split_dates = set(self.mapped('sale_split_date')) - {False, None}
        if len(split_dates) == 1:
            values['sale_split_date'] = split_dates.pop()
        return values

    def _search_picking_for_assignation_domain(self):
        # Only join an existing delivery order planned for the same day.
        domain = super()._search_picking_for_assignation_domain()
        return domain + [('sale_split_date', '=', self.sale_split_date or False)]
